/**
 * How a project connects to the user's Global Brain.
 *
 * Two layers, never mixed:
 *   Global Brain   ~/.gaw/brain (one per person, shared by every project): preferences and decisions
 *   Project Brain  <project>/ai-brain (one per project): goal, rules, skills, history
 *
 * Projects never get their own copies of global preference files, so the live
 * Global Brain is never shadowed by a stale copy. Instead each project gets a
 * generated, read-only summary (ai-brain/local/global-brain.md) for agents that
 * can't read outside the project folder. It is personal, so local/ keeps it out of git.
 */
import fs from 'node:fs';
import path from 'node:path';
import { TEMPLATE_FILES, LOCAL_DIR, ensureLocalDir } from './brainLayout.js';

/** Markdown files that belong to a project (from templates/ai-brain). */
export const PROJECT_BRAIN_FILES = TEMPLATE_FILES;

/** Files that belong to the Global Brain. Older GAW versions also copied these into projects. */
export const GLOBAL_PREFERENCE_FILES = [
  'design-principles.md', 'coding-preferences.md', 'component-preferences.md', 'workflow-preferences.md',
  'tool-preferences.md', 'lessons-learned.md', 'confirmed-preferences.md', 'decision-history.md'
];

export const SNAPSHOT_FILE = `${LOCAL_DIR}/global-brain.md`;
/** Where layout 1 kept the summary (next to the project files, with a .gitignore entry). */
export const LEGACY_SNAPSHOT_FILE = 'global-brain.md';
const SNAPSHOT_ORDER = [
  'identity.md', 'design-principles.md', 'coding-preferences.md', 'component-preferences.md',
  'workflow-preferences.md', 'tool-preferences.md', 'lessons-learned.md', 'confirmed-preferences.md'
];
const RECENT_DECISIONS = 10;

const normalize = (text) => String(text).replace(/^﻿/, '').replace(/\r\n/g, '\n').trim();

/** Add a line to the project's .gitignore if the project uses git. Returns true if added. */
export function ensureGitignored(projectDir, entry) {
  const gitignore = path.join(projectDir, '.gitignore');
  const usesGit = fs.existsSync(path.join(projectDir, '.git')) || fs.existsSync(gitignore);
  if (!usesGit) return false;
  const existing = fs.existsSync(gitignore) ? fs.readFileSync(gitignore, 'utf8') : '';
  if (existing.split(/\r?\n/).some(l => l.trim() === entry)) return false;
  const prefix = existing && !existing.endsWith('\n') ? '\n' : '';
  fs.appendFileSync(gitignore, `${prefix}# GAW: personal summary of your Global Brain (regenerated by gaw)\n${entry}\n`, 'utf8');
  return true;
}

/**
 * Write ai-brain/global-brain.md: the user's Global Brain preferences plus their
 * most recent decisions, marked as generated. Returns { file, tokens }.
 */
export function writeGlobalBrainSnapshot(projectDir, globalBrainDir) {
  const brainDir = path.join(projectDir, 'ai-brain');
  if (!fs.existsSync(brainDir)) return null;

  const parts = [
    '# Global Brain (summary)',
    '',
    `_Generated by GAW from your Global Brain (\`${globalBrainDir}\`). **Do not edit**: change your Global Brain instead (\`gaw brain path\`). Refreshed by \`gaw start\` and \`gaw update\`. Project rules in \`ai-brain/rules.md\` take precedence over everything here._`,
    ''
  ];

  for (const file of SNAPSHOT_ORDER) {
    const full = path.join(globalBrainDir, file);
    if (!fs.existsSync(full)) continue;
    // Shift headings down one level so the summary keeps one top-level title
    const body = normalize(fs.readFileSync(full, 'utf8')).replace(/^(#{1,5}) /gm, '#$1 ');
    if (body) parts.push(body, '');
  }

  const history = path.join(globalBrainDir, 'decision-history.md');
  if (fs.existsSync(history)) {
    const rows = normalize(fs.readFileSync(history, 'utf8')).split('\n').filter(l => /^\|\s*\d{4}-\d{2}-\d{2}/.test(l));
    if (rows.length) {
      parts.push('## Recent decisions', '', '| Date | Category | Decision | Context |', '|---|---|---|---|', ...rows.slice(-RECENT_DECISIONS), '');
    }
  }

  const content = `${parts.join('\n').replace(/\n{3,}/g, '\n\n').trim()}\n`;
  ensureLocalDir(projectDir);
  const file = path.join(brainDir, SNAPSHOT_FILE);
  fs.writeFileSync(file, content, 'utf8');
  // Layout 1 kept a copy at ai-brain/global-brain.md; it is generated, so the stale copy goes
  const legacy = path.join(brainDir, LEGACY_SNAPSHOT_FILE);
  if (fs.existsSync(legacy) && fs.readFileSync(legacy, 'utf8').startsWith('# Global Brain (summary)')) fs.unlinkSync(legacy);
  return { file, tokens: Math.round(content.length / 4) };
}

/**
 * Global preference files that older GAW versions copied into a project.
 * `untouched` match a GAW template exactly (safe to remove: nothing is lost);
 * `edited` were changed by someone (kept: they are deliberate project choices).
 */
export function findLegacyPreferenceCopies(projectDir, templateDirs) {
  const brainDir = path.join(projectDir, 'ai-brain');
  const untouched = [];
  const edited = [];
  for (const file of GLOBAL_PREFERENCE_FILES) {
    const full = path.join(brainDir, file);
    if (!fs.existsSync(full)) continue;
    const content = normalize(fs.readFileSync(full, 'utf8'));
    const matchesTemplate = templateDirs.some(dir => {
      const template = path.join(dir, file);
      return fs.existsSync(template) && normalize(fs.readFileSync(template, 'utf8')) === content;
    });
    (matchesTemplate ? untouched : edited).push(file);
  }
  return { untouched, edited };
}
